// Decodes army share codes, e.g. "h0p11e10_51-1p3e39_48i1x5d1x98u3x26-9x132s2x10-3x0".
// Sections: h = heroes (hero, optional m mode flag, p pet, e equipment_equipment), u = troops, s = spells,
// i / d = Clan Castle troops / spells. Ids map to names through data/ids.json.
const ids = require('./data/ids.json');

const SECTION = /([iuds])((?:\d+x\d+-?)+)/g;
const HEROES = /^h([0-9mpe_-]+)/;
const HERO = /^(\d+)(?:m\d+)?(?:p(\d+))?(?:e([\d_]+))?/;

// Troops that count as one army type when deciding an army's main troop.
const FAMILIES = { 'Dragon Rider': 'Dragon' };
// Main troops that name the army even when the Grand Warden carries Fireball.
const CORE_TROOPS = new Set(['Dragon', 'Thrower', 'Super Bowler', 'Super Dragon', 'Super Yeti', 'Root Rider', 'Balloon']);
const HOUNDS = new Set(['Lava Hound', 'Ice Hound']);
// Troops that support the army and never name it, however many are brought.
const SUPPORT_TROOPS = new Set(['Healer']);
const GRAND_WARDEN = 2;
const FIREBALL = 22;
// Troops below this share of the army's housing space don't make a different variation.
const MINOR_SHARE = 0.05;

const plural = name => name + (/(s|x|ch|sh)$/.test(name) ? 'es' : 's');
const isSiege = name => Object.values(ids.troops).some(t => t.name === name && t.siege);
const named = (table, id) => table[id]?.name ?? `Unknown #${id}`;

function parseCounts(text) {
  const counts = new Map();
  for (const part of text.split('-').filter(Boolean)) {
    const [count, id] = part.split('x').map(Number);
    counts.set(id, (counts.get(id) || 0) + count);
  }
  return [...counts].map(([id, count]) => ({ count, id }));
}

function sections(code) {
  const out = {};
  for (const [, letter, text] of code.matchAll(SECTION)) out[letter] = parseCounts(text);
  return out;
}

// One entry per hero: { hero, pet, equipment } as id strings (pet may be undefined).
function heroParts(code) {
  return (code.match(HEROES)?.[1] || '').split('-').filter(Boolean).map(part => {
    const [, hero, pet, equipment] = part.match(HERO);
    return { hero, pet, equipment: (equipment || '').split('_').filter(Boolean) };
  });
}

function decodeArmy(code) {
  const s = sections(code);
  const list = (items, table) => (items || []).map(({ count, id }) => ({ count, name: named(table, id) }));
  return {
    heroes: heroParts(code).map(h => ({
      name: named(ids.heroes, h.hero),
      pet: h.pet === undefined ? null : named(ids.pets, h.pet),
      equipment: h.equipment.map(id => named(ids.equipment, id)),
    })),
    // Siege Machines are listed after the other troops.
    units: list(s.u, ids.troops).sort((a, b) => isSiege(a.name) - isSiege(b.name)),
    spells: list(s.s, ids.spells),
    clanCastleUnits: list(s.i, ids.troops),
    clanCastleSpells: list(s.d, ids.spells),
  };
}

// Housing space per troop, Siege Machines and unknown troops left out.
function troopSpace(code) {
  return (sections(code).u || []).map(({ count, id }) => ({ count, id, troop: ids.troops[id] }))
    .filter(u => u.troop && !u.troop.siege)
    .map(u => ({ ...u, space: u.count * u.troop.space }));
}

// The troop (family) that fills the most housing space, support troops aside.
function mainTroop(troops) {
  const candidates = troops.filter(u => !SUPPORT_TROOPS.has(u.troop.name));
  const space = new Map();
  for (const u of candidates.length ? candidates : troops) {
    const family = FAMILIES[u.troop.name] || u.troop.name;
    space.set(family, (space.get(family) || 0) + u.space);
  }
  return [...space].sort((a, b) => b[1] - a[1])[0]?.[0] ?? null;
}

function hasWardenFireball(code) {
  const warden = heroParts(code).find(h => Number(h.hero) === GRAND_WARDEN);
  return Boolean(warden?.equipment.includes(String(FIREBALL)));
}

// Troops filling at least MINOR_SHARE of the army's housing space.
function significantTroops(troops) {
  const total = troops.reduce((sum, u) => sum + u.space, 0);
  return troops.filter(u => u.space >= MINOR_SHARE * total);
}

// Army type shown to users: usually named after the main troop. Fireball on the Grand Warden
// names armies built around it rather than around a core troop.
function armyType(code) {
  const troops = troopSpace(code);
  const main = mainTroop(troops);
  if (!main) return 'No troops';
  if (hasWardenFireball(code) && !CORE_TROOPS.has(main)) return 'Fireball';
  if (main === 'Dragon') return 'Dragons & Dragon Riders';
  if (main === 'Balloon' && troops.some(u => HOUNDS.has(u.troop.name))) return 'LaLo';
  return plural(main);
}

// Counts of the things that tell strategies apart. Spells include the Clan Castle's.
function features(code) {
  const s = sections(code);
  const count = (items, table) => {
    const counts = new Map();
    for (const { count, id } of items) counts.set(named(table, id), (counts.get(named(table, id)) || 0) + count);
    return name => counts.get(name) || 0;
  };
  const heroes = decodeArmy(code).heroes;
  const has = hero => (...equipment) => {
    const carried = heroes.find(h => h.name === hero)?.equipment || [];
    return equipment.every(e => carried.includes(e));
  };
  return {
    troop: count(s.u || [], ids.troops),
    spell: count([...(s.s || []), ...(s.d || [])], ids.spells),
    // The hero carrying the Spirit Fox is the one sent in alone under Invisibility.
    foxHero: heroes.find(h => h.pet === 'Spirit Fox')?.name ?? null,
    queen: has('Archer Queen'),
    king: has('Barbarian King'),
    warden: has('Grand Warden'),
    duke: has('Dragon Duke'),
  };
}

